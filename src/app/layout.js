import "./globals.css";
import { poppins } from "@/styles/fonts";
import AuthContextProvider from "@/lib/context/AuthContext";
import ModalProvider from "@/lib/context/ModalContext";
import { languages, fallbackLng } from "./i18n/settings";
import { headers } from "next/headers";
import Head from "next/head";
import { PostHogProvider } from "@/lib/analytics/client";
import LocaleTracker from "./i18n/LocaleTracker";
import CookieConsentTrigger from "./components/CookieConsentTrigger";
import clsx from "clsx";

const baseUrl = "https://www.longitudebrand.com";

export const metadata = {

	metadataBase: new URL(baseUrl),
	title: {
		default: "Longitude Official Site",
		template: "%s | Longitude Official"
	},
	description: "Generated by create next app",
	robots: {
		follow: true,
		index: true
	},
	alternates: {
		canonical: `${baseUrl}/`,
		languages: {
			"en-EN": "/en",
			"fr-FR": "/fr"
		}
	}

};

export async function generateStaticParams() {

	return languages.map((lang) => ({ lang }));

};

export default async function RootLayout({
	children,
}) {

	let lang;

	const headersList = await headers();
	// const cookieStore = await cookies();

	lang = headersList.has("x-language") ? headersList.get("x-languge") : fallbackLng;

	const structuredData = JSON.stringify({
		"@context": "https://schema.org",
		"@type": "Organization",
		name: "Longitude",
		url: baseUrl,
		logo: `${baseUrl}/logo.png`,
	})

	return (

		<html lang={lang}>

			<Head>
				<script type="application/ld+json" dangerouslySetInnerHTML={{ __html: structuredData }} />
			</Head>


			<PostHogProvider
				posthogKey={process.env.NEXT_PUBLIC_POSTHOG_KEY}
				posthogHost={process.env.NEXT_PUBLIC_POSTHOG_HOST}
			>
				<AuthContextProvider>
					<ModalProvider>

						<body className={clsx(poppins.className)}>
							<CookieConsentTrigger />
							<LocaleTracker />
							{children}
							{/* <SpeedInsights /> */}
						</body>

					</ModalProvider>
				</AuthContextProvider>
			</PostHogProvider>


		</html>

	);

};
